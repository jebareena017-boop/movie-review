create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  name text not null,
  gender text not null,
  district text not null,
  movie_name text not null,
  rating smallint not null check (rating between 1 and 5),
  review_text text not null,
  created_at timestamptz not null default now()
);

alter table public.reviews enable row level security;

drop policy if exists "Public can read reviews" on public.reviews;
drop policy if exists "Public can create reviews" on public.reviews;
drop policy if exists "Public can delete reviews" on public.reviews;

create policy "Public can read reviews"
  on public.reviews for select
  to anon, authenticated
  using (true);

create policy "Public can create reviews"
  on public.reviews for insert
  to anon, authenticated
  with check (true);

create policy "Public can delete reviews"
  on public.reviews for delete
  to anon, authenticated
  using (true);

insert into public.reviews (name, gender, district, movie_name, rating, review_text)
select 'Ananya Rao', 'Female', 'Central', 'The Eternal Frame', 5, 'A beautifully layered film that stayed with me long after the final scene.'
where not exists (select 1 from public.reviews);

create table if not exists public.movies (
  id bigint generated by default as identity primary key,
  title text not null,
  genre text not null,
  language text not null,
  release_year smallint not null,
  director text not null,
  description text not null,
  poster_url text,
  created_at timestamptz not null default now()
);

alter table public.movies enable row level security;

drop policy if exists "Public can read movies" on public.movies;
drop policy if exists "Public can create movies" on public.movies;
drop policy if exists "Public can delete movies" on public.movies;

